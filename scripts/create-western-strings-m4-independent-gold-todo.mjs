import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const DEFAULT_BENCHMARK = path.join("data", "experiments", "western-strings-m4", "omr-benchmark.json");
const DEFAULT_OUT_DIR = path.join("data", "experiments", "western-strings-m4");

function parseArgs(argv) {
  const args = {
    benchmark: DEFAULT_BENCHMARK,
    outDir: DEFAULT_OUT_DIR,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--benchmark") args.benchmark = argv[++index] || args.benchmark;
    else if (arg === "--out-dir") args.outDir = argv[++index] || args.outDir;
  }
  return args;
}

function csvEscape(value) {
  const text = value === null || value === undefined ? "" : String(value);
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

async function writeCsv(filePath, rows, columns) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  const text = [
    columns.join(","),
    ...rows.map((row) => columns.map((column) => csvEscape(row[column] ?? "")).join(",")),
  ].join("\n") + "\n";
  await fs.writeFile(filePath, text, "utf8");
}

function buildTodoRows(report) {
  return (report.rows || [])
    .filter((row) => row.goldEqualsDraftHash || row.benchmarkUsable === false)
    .map((row) => ({
      recordingId: row.recordingId || "",
      pieceId: row.pieceId || "",
      issue: row.blockingReason || "benchmark-row-not-usable",
      action: "Create or replace goldPath with an independently human-corrected MusicXML/MXL, then rerun npm run western:m4-omr-benchmark.",
      goldPath: row.goldPath || "",
      draftPath: row.draftPath || "",
      goldEqualsDraftHash: row.goldEqualsDraftHash || "",
      parseOk: row.parseOk ? "yes" : "",
      goldNotes: row.goldNotes ?? "",
      draftNotes: row.draftNotes ?? "",
    }));
}

function buildMarkdown(report, todoRows) {
  const lines = [
    "# M4 Independent Gold TODO",
    "",
    "This file is generated by `npm run western:m4-independent-gold-todo`.",
    "",
    "Purpose: M4 OMR accuracy can only be measured against an independent gold score.",
    "Rows where the approved clean score is byte-identical to the Audiveris draft are blocked as self-comparisons.",
    "",
    "Do not treat the current 100% draft-vs-gold sequence match as OMR evidence when `goldEqualsDraftHash=yes`.",
    "",
    "## Current Summary",
    "",
    `- benchmark rows: ${report.counts?.rows ?? 0}`,
    `- parse OK rows: ${report.counts?.parseOkRows ?? 0}`,
    `- usable benchmark rows: ${report.counts?.usableBenchmarkRows ?? 0}`,
    `- self-comparison rows: ${report.counts?.selfComparisonRows ?? 0}`,
    `- M4 draft quality ready: ${report.gate?.m4OmrDraftQualityReady ? "yes" : "no"}`,
    "",
    "## Human Work Required",
    "",
    "For each row below:",
    "",
    "1. Open the original score image/PDF and the current draft MXL if helpful.",
    "2. Produce an independently checked gold MusicXML/MXL. The draft may be used as a starting point, but it must be verified against the source image and saved as a new human-corrected gold file.",
    "3. Replace `goldPath` or update the clean-score intake to point to the independent gold file.",
    "4. Rerun `npm run western:m4-omr-benchmark`.",
    "5. Only if `usableBenchmarkRows > 0` and quality metrics pass may OMR move toward a release gate. Runtime remains fail-closed until then.",
    "",
    "| # | recordingId | pieceId | issue | goldPath | draftPath |",
    "|---:|---|---|---|---|---|",
  ];
  todoRows.forEach((row, index) => {
    lines.push(
      `| ${index + 1} | ${row.recordingId} | ${row.pieceId} | ${row.issue} | \`${row.goldPath}\` | \`${row.draftPath}\` |`,
    );
  });
  lines.push("");
  return lines.join("\n");
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const benchmarkPath = path.resolve(process.cwd(), args.benchmark);
  const outDir = path.resolve(process.cwd(), args.outDir);
  const report = JSON.parse(await fs.readFile(benchmarkPath, "utf8"));
  const todoRows = buildTodoRows(report);
  const csvPath = path.join(outDir, "independent-gold-todo.csv");
  const mdPath = path.join(outDir, "independent-gold-todo.md");
  await writeCsv(csvPath, todoRows, [
    "recordingId",
    "pieceId",
    "issue",
    "action",
    "goldPath",
    "draftPath",
    "goldEqualsDraftHash",
    "parseOk",
    "goldNotes",
    "draftNotes",
  ]);
  await fs.writeFile(mdPath, buildMarkdown(report, todoRows), "utf8");
  console.log(JSON.stringify({
    ok: true,
    todoRows: todoRows.length,
    benchmark: args.benchmark,
    csv: path.relative(process.cwd(), csvPath).replace(/\\/g, "/"),
    markdown: path.relative(process.cwd(), mdPath).replace(/\\/g, "/"),
    readyForOmrAccuracyClaim: todoRows.length === 0 && Boolean(report.gate?.m4OmrDraftQualityReady),
  }, null, 2));
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
